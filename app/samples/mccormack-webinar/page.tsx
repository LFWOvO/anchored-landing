const TS_RE = /\[(\d{1,2}:\d{2}(?::\d{2})?)–(\d{1,2}:\d{2}(?::\d{2})?)\]/g;
const BOLD_RE = /\*\*(.+?)\*\*/g;

function toSeconds(ts: string): number {
  const parts = ts.split(":").map(Number);
  while (parts.length < 3) parts.unshift(0);
  return parts[0] * 3600 + parts[1] * 60 + parts[2];
}

function renderInline(text: string, keyBase: string): ReactNode[] {
  // 先按时间戳切分，再在每个纯文本段内按粗体切分
  const nodes: ReactNode[] = [];
  let last = 0;
  let k = 0;
  for (const m of text.matchAll(TS_RE)) {
    const before = text.slice(last, m.index);
    nodes.push(...renderBold(before, `${keyBase}-t${k++}`));
    const start = m[1];
    const label = `[${m[1]}–${m[2]}]`;
    nodes.push(
      <a
        key={`${keyBase}-ts${k++}`}
        href={`https://www.youtube.com/watch?v=${VIDEO_ID}&t=${toSeconds(start)}s`}
        target="_blank"
        rel="noopener noreferrer"
        className="whitespace-nowrap rounded bg-slate-100 px-1 py-0.5 font-mono text-[0.78em] text-slate-500 align-middle hover:bg-blue-50 hover:text-blue-700"
      >
        {label}
      </a>,
    );
    last = m.index + m[0].length;
  }
  nodes.push(...renderBold(text.slice(last), `${keyBase}-t${k++}`));
  return nodes;
}

function renderBold(text: string, keyBase: string): ReactNode[] {
  const nodes: ReactNode[] = [];
  let last = 0;
  let k = 0;
  for (const m of text.matchAll(BOLD_RE)) {
    nodes.push(text.slice(last, m.index));
    nodes.push(<strong key={`${keyBase}-b${k++}`} className="font-semibold text-slate-900">{m[1]}</strong>);
    last = m.index + m[0].length;
  }
  nodes.push(text.slice(last));
  return nodes;
}

function renderArticle(src: string): ReactNode[] {
  const lines = src.split("\n");
  const out: ReactNode[] = [];
  let i = 0;
  let key = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === "") { i++; continue; }
    if (line.startsWith("### ")) {
      out.push(<h3 key={key++} className="mt-8 text-xl font-semibold text-slate-900">{renderInline(line.slice(4), `h3-${i}`)}</h3>);
      i++;
    } else if (line.startsWith("## ")) {
      out.push(<h2 key={key++} className="mt-12 text-2xl font-bold text-slate-900">{renderInline(line.slice(3), `h2-${i}`)}</h2>);
      i++;
    } else if (line.startsWith("# ")) {
      out.push(<h1 key={key++} className="text-3xl font-bold leading-tight text-slate-900">{renderInline(line.slice(2), `h1-${i}`)}</h1>);
      i++;
    } else if (line.trim() === "---") {
      out.push(<hr key={key++} className="my-8 border-slate-200" />);
      i++;
    } else if (line.startsWith("|")) {
      const rows: string[] = [];
      while (i < lines.length && lines[i].startsWith("|")) {
        const cells = lines[i].split("|").slice(1, -1);
        const isSeparator = cells.length > 0 && cells.every((c) => /^:?-+:?$/.test(c.trim()));
        if (!isSeparator) rows.push(lines[i]);
        i++;
      }
      const cells = rows.map((r) => r.split("|").slice(1, -1).map((c) => c.trim()));
      const [head, ...body] = cells;
      out.push(
        <div key={key++} className="mt-4 overflow-x-auto">
          <table className="w-full border-collapse text-sm">
            <thead>
              <tr>{head.map((c, ci) => <th key={ci} className="border-b-2 border-slate-300 px-3 py-2 text-left font-semibold text-slate-900">{c}</th>)}</tr>
            </thead>
            <tbody>
              {body.map((row, ri) => (
                <tr key={ri} className="odd:bg-slate-50">
                  {row.map((c, ci) => <td key={ci} className="border-b border-slate-200 px-3 py-2 align-top text-slate-700">{renderInline(c, `td-${ri}-${ci}`)}</td>)}
                </tr>
              ))}
            </tbody>
          </table>
        </div>,
      );
    } else if (line.startsWith("- ")) {
      const items: string[] = [];
      while (i < lines.length && lines[i].startsWith("- ")) { items.push(lines[i].slice(2)); i++; }
      out.push(
        <ul key={key++} className="mt-4 list-disc space-y-2 pl-6 text-slate-700">
          {items.map((it, ii) => <li key={ii}>{renderInline(it, `li-${i}-${ii}`)}</li>)}
        </ul>,
      );
    } else if (/^\d+\. /.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\d+\. /.test(lines[i])) { items.push(lines[i].replace(/^\d+\. /, "")); i++; }
      out.push(
        <ol key={key++} className="mt-4 list-decimal space-y-2 pl-6 text-slate-700">
          {items.map((it, ii) => <li key={ii}>{renderInline(it, `ol-${i}-${ii}`)}</li>)}
        </ol>,
      );
    } else if (line.startsWith("*") && line.endsWith("*") && !line.startsWith("**")) {
      out.push(<p key={key++} className="mt-4 border-l-2 border-slate-200 pl-4 text-sm italic leading-relaxed text-slate-500">{renderInline(line.slice(1, -1), `src-${i}`)}</p>);
      i++;
    } else {
      out.push(<p key={key++} className="mt-4 leading-relaxed text-slate-700">{renderInline(line, `p-${i}`)}</p>);
      i++;
    }
  }
  return out;
}

